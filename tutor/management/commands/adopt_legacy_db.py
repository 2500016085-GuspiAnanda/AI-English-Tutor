"""Perintah sekali jalan: serahkan database lama (dibuat dari schema.sql) ke Django.

Pemakaian:  uv run python manage.py adopt_legacy_db

Tabel lama sudah sama dengan tutor/models.py, kecuali beberapa detail yang Django harapkan berbeda.
Perintah ini merapikan detail itu, lalu menjalankan `migrate --fake-initial`:
migration 0001 app tutor hanya DICATAT sudah jalan (tabelnya memang sudah ada),
sedangkan tabel bawaan Django (auth, admin, sessions, ...) dibuat sungguhan.

Aman dijalankan berulang: setiap langkah dicek dulu, dan database yang sudah diadopsi dilewati.
Database baru (kosong) tidak perlu perintah ini; cukup `manage.py migrate`.
"""
from django.core.management import call_command
from django.core.management.base import BaseCommand
from django.db import connection, transaction

TABLES = ["users", "curriculum_topics", "sessions", "messages", "mistakes", "pattern_progress"]

# Nama foreign key buatan PostgreSQL (schema.sql) -> nama yang dipakai migration Django
FOREIGN_KEYS = {
    "sessions": {"sessions_user_id_fkey": "sessions_user_id_05e26f4a_fk_users_id",
                 "sessions_topic_id_fkey": "sessions_topic_id_25dfd5b1_fk_curriculum_topics_id"},
    "messages": {"messages_session_id_fkey": "messages_session_id_8b58efc4_fk_sessions_id"},
    "mistakes": {"mistakes_user_id_fkey": "mistakes_user_id_7aa5be5e_fk_users_id",
                 "mistakes_session_id_fkey": "mistakes_session_id_aba65f66_fk_sessions_id"},
    "pattern_progress": {"pattern_progress_user_id_fkey": "pattern_progress_user_id_2c237af7_fk_users_id"},
}

# Index yang dibuat Django untuk setiap foreign key dan kolom unik bertipe teks
INDEXES = [
    'CREATE INDEX IF NOT EXISTS "users_username_e8658fc8_like" ON "users" ("username" text_pattern_ops)',
    'CREATE INDEX IF NOT EXISTS "sessions_user_id_05e26f4a" ON "sessions" ("user_id")',
    'CREATE INDEX IF NOT EXISTS "sessions_topic_id_25dfd5b1" ON "sessions" ("topic_id")',
    'CREATE INDEX IF NOT EXISTS "messages_session_id_8b58efc4" ON "messages" ("session_id")',
    'CREATE INDEX IF NOT EXISTS "mistakes_user_id_7aa5be5e" ON "mistakes" ("user_id")',
    'CREATE INDEX IF NOT EXISTS "mistakes_session_id_aba65f66" ON "mistakes" ("session_id")',
    'CREATE INDEX IF NOT EXISTS "pattern_progress_user_id_2c237af7" ON "pattern_progress" ("user_id")',
]


class Command(BaseCommand):
    help = "Serahkan database lama (schema.sql) ke Django lalu jalankan migrate --fake-initial."

    def handle(self, *args, **options):
        existing = set(connection.introspection.table_names())
        if not set(TABLES) <= existing:
            self.stdout.write("Tabel lama tidak lengkap; ini database baru. Jalankan `manage.py migrate` saja.")
            return
        if "django_migrations" in existing:
            with connection.cursor() as cur:
                cur.execute("SELECT 1 FROM django_migrations WHERE app = 'tutor' AND name = '0001_initial'")
                if cur.fetchone():
                    self.stdout.write("Database ini sudah diadopsi. Tidak ada yang diubah.")
                    return

        with transaction.atomic(), connection.cursor() as cur:
            # 1. Django mewajibkan primary key; tabel pattern_progress lama tidak punya.
            cur.execute("SELECT 1 FROM information_schema.columns WHERE table_name = 'pattern_progress' AND column_name = 'id'")
            if not cur.fetchone():
                cur.execute('ALTER TABLE "pattern_progress" ADD COLUMN "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
                self.stdout.write("+ pattern_progress: kolom id (primary key) ditambahkan")

            # 2. GENERATED ALWAYS menolak id yang diisi manual (mis. saat memuat fixture); Django memakai BY DEFAULT.
            for table in TABLES:
                cur.execute(f'ALTER TABLE "{table}" ALTER COLUMN "id" SET GENERATED BY DEFAULT')
            self.stdout.write("+ kolom id semua tabel: GENERATED BY DEFAULT")

            # 3. Samakan nama foreign key dengan migration, dan buat DEFERRABLE seperti buatan Django.
            cur.execute("SELECT conname FROM pg_constraint WHERE contype = 'f' AND connamespace = 'public'::regnamespace")
            fk_names = {row[0] for row in cur.fetchall()}
            for table, renames in FOREIGN_KEYS.items():
                for old, new in renames.items():
                    if old in fk_names:
                        cur.execute(f'ALTER TABLE "{table}" RENAME CONSTRAINT "{old}" TO "{new}"')
                    cur.execute(f'ALTER TABLE "{table}" ALTER CONSTRAINT "{new}" DEFERRABLE INITIALLY DEFERRED')
            self.stdout.write("+ foreign key: nama disamakan dengan Django")

            # 4. Index yang Django harapkan ada.
            for sql in INDEXES:
                cur.execute(sql)
            self.stdout.write("+ index foreign key dibuat")

        self.stdout.write("Menjalankan migrate --fake-initial ...")
        call_command("migrate", fake_initial=True)
        self.stdout.write(self.style.SUCCESS("Selesai: database lama sekarang dikelola Django."))
